import { describe, expect, it } from 'vitest'
import { createInteractionWindow } from '../app/utils/interactionWindow'

describe('interactive terminal episode', () => {
  it('debounces opening, keeps cursor changes live, and closes on a stable field', () => {
    const w = createInteractionWindow()
    expect(w.update('terminal', 0)).toBe(false)
    expect(w.update('terminal', 499)).toBe(false)
    expect(w.update('terminal', 500)).toBe(true)
    expect(w.update('terminal', 800)).toBe(true)
    expect(w.update('input', 1000)).toBe(true)
    expect(w.update('input', 1900)).toBe(false)
  })
  it('does not reopen a dismissed episode after oscillations or missed reads', () => {
    const w = createInteractionWindow()
    w.update('terminal', 0)
    w.update('terminal', 500)
    w.dismiss()
    expect(w.update('terminal', 1000)).toBe(false)
    w.update('native', 1100)
    w.update('unknown', 1200)
    w.update('input', 1300)
    w.update('terminal', 1500)
    expect(w.update('terminal', 2100)).toBe(false)
    w.update('input', 2200)
    w.update('input', 3100)
    w.update('terminal', 3200)
    expect(w.update('terminal', 3700)).toBe(true)
  })
  it('a window reopened after a manual close still closes on a stable field', () => {
    const w = createInteractionWindow()
    w.update('terminal', 0)
    w.update('terminal', 500)
    w.dismiss()
    expect(w.update('terminal', 4000)).toBe(false)
    w.reopen()
    expect(w.update('terminal', 4100)).toBe(true)
    expect(w.update('input', 4200)).toBe(true)
    expect(w.update('input', 5100)).toBe(false)
    // A new episode opens normally again: the reopening left no dismissal.
    w.update('terminal', 5200)
    expect(w.update('terminal', 5700)).toBe(true)
  })
  it('yields on lost state and debounces a fresh terminal observation', () => {
    const w = createInteractionWindow()
    w.update('terminal', 0)
    w.update('terminal', 500)
    expect(w.update('unknown', 1000)).toBe(false)
    expect(w.update('input', 1100)).toBe(false)
    expect(w.update('terminal', 1600)).toBe(false)
    expect(w.update('managed', 1700)).toBe(false)
    expect(w.update('terminal', 1800)).toBe(false)
    expect(w.update('terminal', 2300)).toBe(true)
  })
  it('never reattaches a stale window when returning to a pane already at its field', () => {
    const w = createInteractionWindow()
    w.update('terminal', 0)
    w.update('terminal', 500)
    expect(w.resume('input')).toBe(false)
    expect(w.update('input', 2000)).toBe(false)
  })
  it('immediately yields to every recognized native screen', () => {
    const w = createInteractionWindow()
    w.update('terminal', 0)
    w.update('terminal', 500)
    expect(w.update('native', 600)).toBe(false)
  })

  for (const next of ['working', 'unknown'] as const) it(`closes and never resumes stale state during ${next}`, () => {
    const w = createInteractionWindow()
    w.update('terminal', 0)
    w.update('terminal', 500)
    expect(w.resume(next)).toBe(false)
    w.update('terminal', 1000)
    w.update('terminal', 1500)
    expect(w.update(next, 2000)).toBe(false)
    expect(w.update(next, 120_000)).toBe(false)
  })
  it('starts a new episode after work, including after manual dismissal', () => {
    const w = createInteractionWindow()
    w.dismiss()
    w.update('working', 0)
    w.update('terminal', 1000)
    expect(w.update('terminal', 1500)).toBe(true)
  })
})

describe('interactive terminal deadline', () => {
  it('names the end of the opening debounce, then nothing', () => {
    const w = createInteractionWindow()
    expect(w.deadline()).toBeNull()
    w.update('terminal', 1000)
    expect(w.deadline()).toBe(1500)
    expect(w.update('terminal', 1500)).toBe(true)
    expect(w.deadline()).toBeNull()
  })
  it('names the end of the closing debounce while a window or a dismissal remains', () => {
    const w = createInteractionWindow()
    w.update('terminal', 0)
    w.update('terminal', 500)
    w.update('input', 1000)
    expect(w.deadline()).toBe(1900)
    expect(w.update('input', 1900)).toBe(false)
    expect(w.deadline()).toBeNull()
    w.update('terminal', 2000)
    w.dismiss()
    expect(w.deadline()).toBeNull()
    w.update('input', 3000)
    expect(w.deadline()).toBe(3900)
    w.update('input', 3900)
    expect(w.deadline()).toBeNull()
  })
  it('has none for a field at rest, work, a native card or a dismissed terminal', () => {
    for (const kind of ['input', 'working', 'native', 'managed', 'unknown'] as const) {
      const w = createInteractionWindow()
      w.update(kind, 0)
      expect(w.deadline()).toBeNull()
    }
  })
  it('a single update at the deadline matches the former 100 ms polling', () => {
    const polled = createInteractionWindow()
    const timed = createInteractionWindow()
    polled.update('terminal', 40)
    timed.update('terminal', 40)
    let opened = -1
    for (let now = 100; now <= 700 && opened < 0; now += 100) if (polled.update('terminal', now)) opened = now
    expect(opened).toBe(600)
    expect(timed.update('terminal', timed.deadline()!)).toBe(true)
    expect(timed.deadline()).toBe(null)
  })
  it('tells its subscribers of a dismissal or a reopening, until they leave', () => {
    const w = createInteractionWindow()
    let calls = 0
    const leave = w.subscribe(() => { calls++ })
    w.reopen()
    w.dismiss()
    expect(calls).toBe(2)
    leave()
    w.reopen()
    expect(calls).toBe(2)
  })
})
